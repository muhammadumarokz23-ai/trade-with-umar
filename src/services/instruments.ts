export function getInstrument(symbol: string): InstrumentInfo {
  const found = SUPPORTED_INSTRUMENTS.find(i => i.symbol.toUpperCase() === symbol.toUpperCase());
  if (found) return found;
  return {
    symbol: symbol.toUpperCase(),
    name: symbol.toUpperCase(),
    market: symbol.includes('USDT') ? 'crypto' : symbol.length <= 4 ? 'stock' : 'forex',
    baseAsset: symbol.slice(0, 3),
    quoteAsset: symbol.slice(3) || 'USD',
    precision: 2,
    tickSize: 0.01,
    contractSize: 1,
    is24_7: symbol.includes('USDT'),
    spreadTypicalPips: 1.0,
    description: 'Configurable institutional trading instrument',
  };
}

export function getInstrumentsByMarket(market: MarketType): InstrumentInfo[] {
  return SUPPORTED_INSTRUMENTS.filter(i => i.market === market);
}
